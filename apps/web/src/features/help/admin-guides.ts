export function allowedGuides(profile: Pick<AdminProfile, "capabilities">) {
  return adminGuides.filter(
    (guide) =>
      !guide.capability || profile.capabilities.includes(guide.capability),
  );
}
export function guideForPath(
  path: string,
  profile: Pick<AdminProfile, "capabilities">,
) {
  return (
    allowedGuides(profile).find((guide) => guide.match.test(path)) ||
    adminGuides.at(-1)!
  );
}
